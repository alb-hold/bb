export const SERVER_HTTP_DRAIN_TIMEOUT_MS = 500;
export const SERVER_HTTP_CLOSE_WAIT_TIMEOUT_MS = 50;
export const SERVER_TERMINAL_OUTPUT_FLUSH_TIMEOUT_MS = 250;
export const SERVER_PLUGIN_SHUTDOWN_TIMEOUT_MS = 3_000;
export const SERVER_WEBSOCKET_SHUTDOWN_WAIT_TIMEOUT_MS = 100;
export const SERVER_SHUTDOWN_BOUND_MS =
  SERVER_HTTP_DRAIN_TIMEOUT_MS +
  SERVER_WEBSOCKET_SHUTDOWN_WAIT_TIMEOUT_MS +
  SERVER_TERMINAL_OUTPUT_FLUSH_TIMEOUT_MS +
  SERVER_HTTP_CLOSE_WAIT_TIMEOUT_MS * 2 +
  SERVER_PLUGIN_SHUTDOWN_TIMEOUT_MS;
export const DAEMON_DETACH_HEAD_START_MARGIN_MS = 1_250;
export const MEASURED_MAX_DAEMON_STOP_STEP_MS = 4_736;
export const DAEMON_DETACH_HEAD_START_MS =
  Math.ceil(
    (MEASURED_MAX_DAEMON_STOP_STEP_MS +
      DAEMON_DETACH_HEAD_START_MARGIN_MS) /
      1_000,
  ) *
  1_000;
export const SERVER_SHUTDOWN_SAFETY_MARGIN_MS = 250;
export const MANAGED_PROCESS_KILL_WAIT_TIMEOUT_MS =
  SERVER_SHUTDOWN_SAFETY_MARGIN_MS * 2;
export const SERVER_PROCESS_TERMINATION_TIMEOUT_MS =
  SERVER_SHUTDOWN_BOUND_MS +
  SERVER_SHUTDOWN_SAFETY_MARGIN_MS * 2;
export const DAEMON_PROCESS_TERMINATION_TIMEOUT_MS =
  DAEMON_DETACH_HEAD_START_MS +
  SERVER_SHUTDOWN_BOUND_MS +
  SERVER_SHUTDOWN_SAFETY_MARGIN_MS * 2;
export const DESKTOP_SHUTDOWN_OUTER_MARGIN_MS = 800;
export const LAUNCHER_MAX_SHUTDOWN_MS = Math.max(
  DAEMON_DETACH_HEAD_START_MS +
    SERVER_PROCESS_TERMINATION_TIMEOUT_MS,
  DAEMON_PROCESS_TERMINATION_TIMEOUT_MS,
) + MANAGED_PROCESS_KILL_WAIT_TIMEOUT_MS;
export const DESKTOP_OWNED_RUNTIME_SHUTDOWN_GRACE_MS =
  LAUNCHER_MAX_SHUTDOWN_MS + DESKTOP_SHUTDOWN_OUTER_MARGIN_MS;
